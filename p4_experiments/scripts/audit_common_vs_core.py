"""Audit common/ vs core/ to identify wrappers vs divergent forks.

Read-only. Writes a report to `p4_experiments/common/COMMON_VS_CORE_AUDIT.md`.
"""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path

_P4_ROOT = Path(__file__).resolve().parents[1]
CORE = _P4_ROOT / "core"
COMMON = _P4_ROOT / "common"


def _sha8(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()[:8]


def main() -> None:
    pairs = sorted(
        {p.name for p in CORE.glob("*.py")}
        & {p.name for p in COMMON.glob("*.py")}
    )

    lines = [
        "# common/ vs core/ audit",
        "",
        "_Read-only audit generated by `p4_experiments/scripts/audit_common_vs_core.py`._",
        "_No files were modified by this script._",
        "",
        "| File | core size | core sha | common size | common sha | classification |",
        "| --- | ---: | --- | ---: | --- | --- |",
    ]

    for name in pairs:
        a = (CORE / name).read_bytes()
        b = (COMMON / name).read_bytes()
        if a == b:
            kind = "**identical** \u2014 safe to collapse"
        elif len(b) < 0.25 * len(a) and (b"from p4_experiments.core" in b
                                          or b"from ..core" in b
                                          or b"from core" in b):
            kind = "wrapper (small re-export)"
        else:
            kind = "**divergent** \u2014 investigate before collapsing"
        lines.append(
            f"| `{name}` | {len(a)} | `{_sha8(a)}` | {len(b)} | `{_sha8(b)}` | {kind} |"
        )

    out = COMMON / "COMMON_VS_CORE_AUDIT.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out.relative_to(_P4_ROOT)}")
    print(f"  pairs: {len(pairs)}")


if __name__ == "__main__":
    main()
